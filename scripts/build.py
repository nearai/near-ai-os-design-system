# ---------------------------------------------------------------------------
# Springs
# ---------------------------------------------------------------------------
def spring_curve(stiffness, damping, points=17):
    """A damped spring (mass 1) as CSS linear() stops and its settle time."""
    w0 = math.sqrt(stiffness)
    z = damping

    def x(t):
        if z < 1:
            wd = w0 * math.sqrt(1 - z * z)
            return 1 - math.exp(-z * w0 * t) * (math.cos(wd * t) + (z * w0 / wd) * math.sin(wd * t))
        return 1 - math.exp(-w0 * t) * (1 + w0 * t)

    t, dt, last_out = 0.0, 0.001, 0.0
    while t < 5:
        if abs(x(t) - 1) > 0.001:
            last_out = t
        t += dt
    settle = last_out + dt
    vals = [x(settle * i / (points - 1)) for i in range(points)]
    vals[0], vals[-1] = 0, 1
    body = ', '.join(('%.3f' % v).rstrip('0').rstrip('.') if v not in (0, 1) else str(int(v)) for v in vals)
    return 'linear(%s)' % body, round(settle * 1000)


def spring_response(stiffness):
    """SwiftUI's response for a mass-1 spring of this stiffness."""
    return 2 * math.pi / math.sqrt(stiffness)


