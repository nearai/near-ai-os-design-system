def theme_block(art, theme_id, selector, scheme):
    lines = ['  color-scheme: %s;' % scheme]
    for t in art['color']['tokens']:
        if isinstance(t['value'], dict):
            lines.append('  --%s: %s;' % (t['name'], t['value'][theme_id]))
    for t in art['shadow']['tokens']:
        lines.append('  --%s: %s;' % (t['name'], t['value'][theme_id]))
    return '%s {\n%s\n}' % (selector, '\n'.join(lines))


def tokens_css(src, art):
    by = {t['id']: t for t in src['themes']}
    out = ['/* %s — CSS custom properties. %s */' % (src['name'], HEADER),
           '/* Set data-theme on <html> to choose a theme. With no data-theme, the parent theme follows',
           '   prefers-color-scheme and prefers-contrast. */',
           theme_block(art, 'light', ':root', 'light'),
           '@media (prefers-color-scheme: dark) {\n' + theme_block(art, 'dark', ':root:not([data-theme])', 'dark') + '\n}',
           '@media (prefers-contrast: more) {\n' + theme_block(art, 'light-hc', ':root:not([data-theme])', 'light') + '\n}',
           '@media (prefers-contrast: more) and (prefers-color-scheme: dark) {\n'
           + theme_block(art, 'dark-hc', ':root:not([data-theme])', 'dark') + '\n}']
    for tid, t in by.items():
        out.append(theme_block(art, tid, '[data-theme="%s"]' % tid, t['appearance']))
    root = []
    for t in art['color']['tokens']:
        if isinstance(t['value'], str):
            root.append('  --%s: %s;' % (t['name'], t['value']))
    for key in ('spacing', 'radius', 'size', 'opacity', 'blur', 'zIndex', 'breakpoint', 'duration', 'easing'):
        for t in art[key]['tokens']:
            root.append('  --%s: %s;' % (t['name'], t['value']))
    for k, stack in art['type']['families'].items():
        root.append('  --font-%s: %s;' % (k, stack))
    out.append(':root {\n%s\n}' % '\n'.join(root))
    for g in art['type']['groups']:
        for s in g['styles']:
            decl = ['font-family: var(--font-%s)' % s.get('family', g['family']), 'font-size: %s' % s['fontSize'],
                    'line-height: %s' % s['lineHeight'], 'font-weight: %s' % s['fontWeight']]
            if 'letterSpacing' in s:
                decl.append('letter-spacing: %s' % s['letterSpacing'])
            out.append('.%s { %s; }' % (s['name'], '; '.join(decl)))
    return '\n'.join(out) + '\n'


def component_css(src):
    parts = sorted(p for p in os.listdir(os.path.join(ROOT, 'css')) if p.endswith('.css'))
    css = ['/* %s — component stylesheet. Load after tokens.css. %s */' % (src['name'], HEADER.replace('tokens/near-ai.tokens.json', 'css/*.css'))]
    for p in parts:
        with open(os.path.join(ROOT, 'css', p)) as f:
            css.append(f.read().strip())
    return '\n\n'.join(css) + '\n'


def tailwind_css(src, art):
    out = ['/* %s — Tailwind CSS v4 theme. %s */' % (src['name'], HEADER),
           '/* Import tokens.css first; colors resolve per theme through its custom properties.',
           '   @import "tailwindcss"; @import "<pkg>/dist/css/tokens.css"; @import "<pkg>/dist/tailwind/theme.css"; */',
           '@theme inline {']
    for t in art['color']['tokens']:
        out.append('  --color-%s: var(--%s);' % (t['name'], t['name']))
    for n, t in src['spacing']['tokens'].items():
        if not n.startswith('space-'):
            out.append('  --spacing-%s: %s;' % (n, t['value']))
    for n, t in src['radius']['tokens'].items():
        out.append('  --%s: %s;' % (n, t['value']))
    web = [t for t in src['type']['tiers'] if t['id'] == 'web'][0]
    for step, s in web['styles'].items():
        out.append('  --text-%s: %dpx;' % (step, s['size']))
        out.append('  --text-%s--line-height: %dpx;' % (step, s['lineHeight']))
        out.append('  --text-%s--font-weight: %d;' % (step, s['weight']))
        if s['tracking']:
            out.append('  --text-%s--letter-spacing: %gpx;' % (step, s['tracking']))
    out.append('  --font-sans: %s;' % src['type']['families']['web'])
    out.append('  --font-mono: %s;' % src['type']['families']['mono'])
    for n, t in src['breakpoint']['tokens'].items():
        out.append('  --breakpoint-%s: %s;' % (n[3:], t['value']))
    for t in art['easing']['tokens']:
        if t['name'].startswith(('ease-', 'spring-')):
            name = t['name'][5:] if t['name'].startswith('ease-') else t['name']
            out.append('  --ease-%s: %s;' % (name, t['value']))
    out.append('}')
    return '\n'.join(out) + '\n'


