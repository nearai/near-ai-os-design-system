def camel(name):
    parts = re.split(r'[-.]', name)
    head = parts[0]
    tail = ''.join(p.upper() if p == 'hc' else p[:1].upper() + p[1:] for p in parts[1:])
    return head + tail


def num(value):
    m = re.match(r'^(-?[0-9.]+)', str(value))
    return float(m.group(1)) if m else None


def fmt(x):
    return ('%.4f' % x).rstrip('0').rstrip('.')


def swift_color(hx):
    r, g, b, a = hex_to_rgba(hx)
    return 'Color(.sRGB, red: %s, green: %s, blue: %s, opacity: %s)' % (fmt(r), fmt(g), fmt(b), fmt(a))


def kotlin_color(hx):
    r, g, b, a = (round(c * 255) for c in hex_to_rgba(hx))
    return 'Color(0x%02X%02X%02X%02X)' % (a, r, g, b)


SWIFT_STYLE = {'caption2': '.caption2', 'caption1': '.caption', 'caption': '.caption', 'footnote': '.footnote',
               'subheadline': '.subheadline', 'callout': '.callout', 'body': '.body', 'headline': '.headline',
               'title3': '.title3', 'title2': '.title2', 'title': '.title', 'title1': '.title',
               'largeTitle': '.largeTitle'}
SWIFT_WEIGHT = {400: '.regular', 500: '.medium', 600: '.semibold', 700: '.bold'}


def swift(src, art):
    themes = src['themes']
    roles = list(src['color'])
    L = ['// %s' % HEADER, '// %s %s' % (src['name'], src['version']), '', 'import SwiftUI', '',
         '/// The six themes: the parent, its increased-contrast pair, and the Trace product.',
         'public enum NearAITheme: String, CaseIterable, Sendable {']
    for t in themes:
        L.append('    case %s = "%s"' % (camel(t['id']), t['id']))
    L += ['', '    public var colors: NearAIColors {', '        switch self {']
    for t in themes:
        L.append('        case .%s: return .%s' % (camel(t['id']), camel(t['id'])))
    L += ['        }', '    }', '}', '', '/// Color roles. Use roles, never brand constants, on controls.',
          'public struct NearAIColors: Sendable {']
    for r in roles:
        L.append('    /// %s' % src['color'][r]['usage'].split('. ')[0].rstrip('.') + '.')
        L.append('    public let %s: Color' % camel(r))
    L.append('}')
    L.append('')
    L.append('public extension NearAIColors {')
    for t in themes:
        L.append('    static let %s = NearAIColors(' % camel(t['id']))
        args = ['        %s: %s' % (camel(r), swift_color(src['color'][r]['values'][t['id']])) for r in roles]
        L.append(',\n'.join(args))
        L.append('    )')
    L += ['}', '', '/// Brand constants for marks and illustration only.', 'public enum NearAIBrand {']
    for n, b in src['brand'].items():
        L.append('    public static let %s = %s' % (camel(n), swift_color(b['value'])))
    L.append('}')
    for key, enum in (('spacing', 'NearAISpacing'), ('radius', 'NearAIRadius'), ('size', 'NearAISize'),
                      ('breakpoint', 'NearAIBreakpoint')):
        L += ['', 'public enum %s {' % enum]
        for n, t in src[key]['tokens'].items():
            v = num(t['value'])
            L.append('    /// %s' % t['usage'])
            L.append('    public static let %s: CGFloat = %s' % (camel(n), fmt(v)))
        L.append('}')
    L += ['', 'public enum NearAIOpacity {']
    for n, t in src['opacity']['tokens'].items():
        L.append('    public static let %s: Double = %s' % (camel(n.replace('opacity-', '')), t['value']))
    L += ['}', '', '/// Backdrop blur for surfaces without a native material.', 'public enum NearAIBlur {']
    for n, t in src['blur']['tokens'].items():
        rad = re.search(r'blur\(([0-9.]+)px\)', t['value'])
        sat = re.search(r'saturate\(([0-9.]+)%\)', t['value'])
        L.append('    public static let %sRadius: CGFloat = %s' % (camel(n.replace('blur-', '')), rad.group(1)))
        if sat:
            L.append('    public static let %sSaturation: Double = %s' % (camel(n.replace('blur-', '')), fmt(float(sat.group(1)) / 100)))
    L += ['}', '', '/// Motion. Check accessibilityReduceMotion before animating; nothing moves when it is on.',
          'public enum NearAIMotion {']
    for n, t in src['motion']['durations'].items():
        L.append('    public static let %s: Double = %s' % (camel(n), fmt(num(t['value']) / 1000)))
    L.append('    /// The one curve (ease-standard) for fades, fills, hover and press.')
    L.append('    public static func standard(_ duration: Double = durationStandard) -> Animation {')
    L.append('        .timingCurve(0.2, 0.8, 0.2, 1, duration: duration)')
    L.append('    }')
    for n, s in src['motion']['springs'].items():
        L.append('    /// %s' % s['usage'])
        L.append('    public static let %s = Animation.spring(response: %s, dampingFraction: %s)'
                 % (camel(n), fmt(spring_response(s['stiffness'])), fmt(s['damping'])))
    L += ['}', '', '/// One type step on one platform tier.', 'public struct NearAITypeStep: Sendable {',
          '    public let size: CGFloat', '    public let lineHeight: CGFloat', '    public let weight: Font.Weight',
          '    public let tracking: CGFloat', '    public let textStyle: Font.TextStyle', '    public let monospaced: Bool', '',
          '    /// The step as a system font on its text style, so it follows the person\'s text size.',
          '    public var font: Font {', '        Font.system(textStyle, design: monospaced ? .monospaced : .default).weight(weight)',
          '    }', '}', '', 'public enum NearAIType {']
    for tier in src['type']['tiers']:
        if tier['id'] not in ('mac', 'ios'):
            continue
        L.append('    public enum %s {' % ('Mac' if tier['id'] == 'mac' else 'IOS'))
        for step, s in tier['styles'].items():
            style = s['maps'].split(' ')[0]
            L.append('        public static let %s = NearAITypeStep(size: %s, lineHeight: %s, weight: %s, tracking: %s, '
                     'textStyle: %s, monospaced: %s)' % (camel(step), s['size'], s['lineHeight'], SWIFT_WEIGHT[s['weight']],
                                                       fmt(s['tracking']), SWIFT_STYLE[style],
                                                       'true' if step == 'mono' else 'false'))
        L.append('    }')
    L.append('}')
    return '\n'.join(L) + '\n'


def kotlin(src, art):
    themes = src['themes']
    roles = list(src['color'])
    L = ['// %s' % HEADER, '// %s %s' % (src['name'], src['version']), '', 'package ai.near.design', '',
         'import androidx.compose.animation.core.SpringSpec', 'import androidx.compose.animation.core.spring',
         'import androidx.compose.runtime.Immutable', 'import androidx.compose.ui.graphics.Color',
         'import androidx.compose.ui.text.TextStyle', 'import androidx.compose.ui.text.font.FontFamily',
         'import androidx.compose.ui.text.font.FontWeight', 'import androidx.compose.ui.unit.dp',
         'import androidx.compose.ui.unit.sp', '',
         '/** Color roles. Use roles, never brand constants, on controls. */', '@Immutable', 'data class NearAIColors(']
    L.append(',\n'.join('    val %s: Color' % camel(r) for r in roles))
    L += [')', '', 'object NearAIThemes {']
    for t in themes:
        L.append('    val %s = NearAIColors(' % (camel(t['id'])[:1].upper() + camel(t['id'])[1:]))
        L.append(',\n'.join('        %s = %s' % (camel(r), kotlin_color(src['color'][r]['values'][t['id']])) for r in roles))
        L.append('    )')
    L.append('')
    L.append('    fun forId(id: String): NearAIColors = when (id) {')
    for t in themes:
        L.append('        "%s" -> %s' % (t['id'], camel(t['id'])[:1].upper() + camel(t['id'])[1:]))
    L += ['        else -> Light', '    }', '}', '', '/** Brand constants for marks and illustration only. */',
          'object NearAIBrand {']
    for n, b in src['brand'].items():
        L.append('    val %s = %s' % (camel(n), kotlin_color(b['value'])))
    L.append('}')
    for key, obj in (('spacing', 'NearAISpacing'), ('radius', 'NearAIRadius'), ('size', 'NearAISize'),
                     ('breakpoint', 'NearAIBreakpoint')):
        L += ['', 'object %s {' % obj]
        for n, t in src[key]['tokens'].items():
            L.append('    /** %s */' % t['usage'].replace('*/', '* /'))
            L.append('    val %s = %s.dp' % (camel(n), fmt(num(t['value']))))
        L.append('}')
    L += ['', 'object NearAIOpacity {']
    for n, t in src['opacity']['tokens'].items():
        L.append('    const val %s = %sf' % (camel(n.replace('opacity-', '')), t['value']))
    L += ['}', '', '/** Motion. Honor the system remove-animations setting: nothing moves when it is on. */',
          'object NearAIMotion {']
    for n, t in src['motion']['durations'].items():
        L.append('    const val %sMillis = %d' % (camel(n), int(num(t['value']))))
    for n, s in src['motion']['springs'].items():
        L.append('    /** %s */' % s['usage'])
        L.append('    fun <T> %s(): SpringSpec<T> = spring(dampingRatio = %sf, stiffness = %sf)'
                 % (camel(n), fmt(s['damping']), fmt(s['stiffness'])))
    L += ['}', '', '/** The Android touch tier: each step is an M3 type role in sp. */', 'object NearAIType {']
    tier = [t for t in src['type']['tiers'] if t['id'] == 'android'][0]
    for step, s in tier['styles'].items():
        fam = 'FontFamily.Monospace' if step == 'mono' else 'FontFamily.Default'
        L.append('    /** %s (%s) */' % (src['type']['steps'][step]['usage'].rstrip('.'), s['maps']))
        L.append('    val %s = TextStyle(fontFamily = %s, fontSize = %s.sp, lineHeight = %s.sp, fontWeight = FontWeight(%d), letterSpacing = %s.sp)'
                 % (camel(step), fam, s['size'], s['lineHeight'], s['weight'], fmt(s['tracking']) if s['tracking'] else '0'))
    L.append('}')
    return '\n'.join(L) + '\n'


def dtcg(src, art, theme):
    def entry(t, v, desc):
        return {'$type': t, '$value': v, '$description': desc}
    out = {'$description': '%s, theme %s. %s' % (src['name'], theme['id'], HEADER),
           'color': {n: entry('color', r['values'][theme['id']], r['usage']) for n, r in src['color'].items()},
           'brand': {n: entry('color', b['value'], b['usage']) for n, b in src['brand'].items()}}
    for key in ('spacing', 'radius', 'size', 'breakpoint'):
        out[key] = {n: entry('dimension', t['value'], t['usage']) for n, t in src[key]['tokens'].items()}
    out['opacity'] = {n: entry('number', float(t['value']), t['usage']) for n, t in src['opacity']['tokens'].items()}
    out['duration'] = {t['name']: entry('duration', t['value'], t['usage']) for t in art['duration']['tokens']}
    out['easing'] = {'ease-standard': entry('cubicBezier', [0.2, 0.8, 0.2, 1], src['motion']['easings']['ease-standard']['usage'])}
    out['fontFamily'] = {k: entry('fontFamily', v, '') for k, v in src['type']['families'].items()}
    typ = {}
    for tier in src['type']['tiers']:
        typ[tier['id']] = {step: entry('typography', {
            'fontFamily': '{fontFamily.%s}' % ('mono' if step == 'mono' else tier['family']),
            'fontSize': '%dpx' % s['size'], 'fontWeight': s['weight'], 'lineHeight': '%dpx' % s['lineHeight'],
            'letterSpacing': '%gpx' % s['tracking']}, src['type']['steps'][step]['usage']) for step, s in tier['styles'].items()}
    out['typography'] = typ
    return out


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


def build(out_dir):
    src = load()
    art = artifact_tokens(src)
    write(os.path.join(out_dir, 'artifact', 'tokens.json'), json.dumps(art, indent=2, ensure_ascii=False) + '\n')
    write(os.path.join(out_dir, 'css', 'tokens.css'), tokens_css(src, art))
    write(os.path.join(out_dir, 'css', 'near-ai.css'), component_css(src))
    write(os.path.join(out_dir, 'tailwind', 'theme.css'), tailwind_css(src, art))
    write(os.path.join(out_dir, 'swift', 'NearAITokens.swift'), swift(src, art))
    write(os.path.join(out_dir, 'compose', 'NearAITokens.kt'), kotlin(src, art))
    for theme in src['themes']:
        write(os.path.join(out_dir, 'dtcg', '%s.tokens.json' % theme['id']),
              json.dumps(dtcg(src, art, theme), indent=2, ensure_ascii=False) + '\n')
    report = [{'theme': t, 'token': tok, 'check': label, 'ratio': ratio, 'floor': floor, 'pass': ratio >= floor - 1e-9}
              for t, tok, label, ratio, floor in checks(src)]
    write(os.path.join(out_dir, 'contrast-report.json'), json.dumps(report, indent=1) + '\n')
    return art


