def flagged_notes(src):
    notes = {}
    for tid, token, label, ratio, floor in checks(src):
        if ratio < floor - 1e-9:
            notes.setdefault(token, []).append('%s %.2f:1 (%s)' % (tid, ratio, label))
    return notes


def artifact_tokens(src):
    themes = [t['id'] for t in src['themes']]
    flagged = flagged_notes(src)
    colors = []
    for name, role in src['color'].items():
        usage = role['usage']
        if name in flagged:
            usage += ' Below the floor, kept from the source and flagged: ' + '; '.join(flagged[name]) + '.'
        colors.append({'name': name, 'value': {t: role['values'][t] for t in themes}, 'usage': usage})
    for name, b in src['brand'].items():
        colors.append({'name': name, 'value': b['value'], 'usage': b['usage']})

    steps = src['type']['steps']
    groups = []
    for tier in src['type']['tiers']:
        styles = []
        for step, s in tier['styles'].items():
            usage = '%s %s: %s.' % (steps[step]['usage'], 'Maps to' if tier['id'] != 'web' else 'Step', s['maps'])
            if step == 'eyebrow':
                usage += ' Uppercase.'
            if step == 'number':
                usage += ' Tabular digits.'
            st = {'name': '%s-%s' % (tier['id'], step), 'fontSize': '%dpx' % s['size'],
                  'lineHeight': '%dpx' % s['lineHeight'], 'fontWeight': s['weight'],
                  'sample': steps[step]['sample'], 'usage': usage}
            if s['tracking']:
                st['letterSpacing'] = '%gpx' % s['tracking']
            if step == 'mono':
                st['family'] = 'mono'
            styles.append(st)
        groups.append({'name': tier['name'], 'family': tier['family'], 'note': tier['note'], 'styles': styles})
    hero = src['type']['hero']
    hstyles = []
    for name, s in hero['styles'].items():
        st = {'name': name, 'fontSize': '%dpx' % s['size'], 'lineHeight': '%dpx' % s['lineHeight'],
              'fontWeight': s['weight']}
        if s['tracking']:
            st['letterSpacing'] = '%gpx' % s['tracking']
        st['sample'] = s['sample']
        st['usage'] = s['usage']
        hstyles.append(st)
    groups.append({'name': hero['name'], 'family': hero['family'], 'note': hero['note'], 'styles': hstyles})

    def fam(key):
        f = src[key]
        return {'note': f['note'], 'tokens': [{'name': n, 'value': t['value'], 'usage': t['usage']}
                                               for n, t in f['tokens'].items()]}

    motion = src['motion']
    durations = [{'name': n, 'value': t['value'], 'usage': t['usage']} for n, t in motion['durations'].items()]
    easings = [{'name': n, 'value': t['value'], 'usage': t['usage']} for n, t in motion['easings'].items()]
    for name, s in motion['springs'].items():
        lin, ms = spring_curve(s['stiffness'], s['damping'])
        easings.append({'name': name, 'value': lin,
                        'usage': '%s Stiffness %d, damping ratio %.2f; settles in %d ms (use duration-%s). '
                                 'Native: spring(stiffness, damping) on SwiftUI and Compose.'
                                 % (s['usage'], s['stiffness'], s['damping'], ms, name)})
        durations.append({'name': 'duration-' + name, 'value': '%dms' % ms,
                          'usage': 'Settle time of %s, to pair with its linear() curve on web.' % name})
    shadow = {'note': src['shadow']['note'],
              'tokens': [{'name': n, 'value': t['values'], 'usage': t['usage']} for n, t in src['shadow']['tokens'].items()]}
    out = {
        'name': src['name'], 'version': 1, 'meta': src['meta'],
        'color': {'themes': [{'id': t['id'], 'name': t['name']} for t in src['themes']], 'tokens': colors},
        'type': {'fonts': [], 'families': src['type']['families'], 'groups': groups},
        'spacing': fam('spacing'), 'radius': fam('radius'), 'shadow': shadow, 'size': fam('size'),
        'opacity': fam('opacity'), 'blur': fam('blur'), 'zIndex': fam('zIndex'), 'breakpoint': fam('breakpoint'),
        'duration': {'note': 'Durations. Nothing moves under Reduce Motion (prefers-reduced-motion): a change jumps to its end state.',
                     'tokens': durations},
        'easing': {'note': 'The one curve for non-spatial change; springs for anything that moves. linear() curves are the web rendering of the native springs.',
                   'tokens': easings},
    }
    return out


